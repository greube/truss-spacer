#!/usr/bin/env python3
"""Build js/fixtures-data.js, the offline fixture wattage database.

Sources, merged in this order (later ones win when the same fixture appears twice):
  1. Open Fixture Library (MIT licence): fixtures with a physical.power value.
     Pass the path to a checkout's fixtures/ folder, e.g.
       git clone --depth 1 --filter=blob:none --sparse https://github.com/OpenLightingProject/open-fixture-library ofl
       git -C ofl sparse-checkout set fixtures
  2. data/touring-fixtures.json: curated touring and rental fixtures, each with the
     manufacturer spec-sheet source it came from.

Usage: python3 tools/build-fixtures.py path/to/ofl/fixtures
The output is plain JavaScript (window.TS.FIXTURES) so the app still works from file://.
"""
import glob, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def norm(s):
    return re.sub(r"[^a-z0-9]+", "", s.lower())

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def main(ofl_dir):
    rows = {}  # norm(m)+"/"+norm(n) -> entry

    mans = json.load(open(os.path.join(ofl_dir, "manufacturers.json")))
    ofl_count = 0
    for path in sorted(glob.glob(os.path.join(ofl_dir, "*", "*.json"))):
        man_key = os.path.basename(os.path.dirname(path))
        try:
            fx = json.load(open(path))
        except ValueError:
            continue
        watts = (fx.get("physical") or {}).get("power")
        if not isinstance(watts, (int, float)) or watts <= 0:
            continue
        m = (mans.get(man_key) or {}).get("name", man_key)
        n = fx.get("name", "").strip()
        if not n:
            continue
        key = "ofl:" + man_key + "/" + os.path.splitext(os.path.basename(path))[0]
        rows[norm(m) + "/" + norm(n)] = [key, m, n, round(watts), "o", ""]
        ofl_count += 1

    curated = json.load(open(os.path.join(ROOT, "data", "touring-fixtures.json")))
    for f in curated["fixtures"]:
        w = f["w"]
        assert isinstance(w, (int, float)) and 0 < w < 20000, f
        assert f.get("url"), f
        src = "l" if f.get("kind") == "rated" else "s"
        key = "db:" + slug(f["m"]) + "/" + slug(f["n"])
        rows[norm(f["m"]) + "/" + norm(f["n"])] = [key, f["m"], f["n"], round(w), src, f["url"]]

    data = sorted(rows.values(), key=lambda r: (r[1].lower(), r[2].lower()))
    keys = [r[0] for r in data]
    assert len(keys) == len(set(keys)), "duplicate keys"

    try:
        ofl_rev = subprocess.run(["git", "-C", ofl_dir, "log", "-1", "--format=%h %cs"],
                                 capture_output=True, text=True).stdout.strip()
    except OSError:
        ofl_rev = "unknown"

    out = os.path.join(ROOT, "js", "fixtures-data.js")
    with open(out, "w") as fh:
        fh.write("/* Truss Spacer fixture wattages. Generated by tools/build-fixtures.py: do not edit by hand.\n")
        fh.write("   Each row: [key, manufacturer, model, max watts, source, source URL]\n")
        fh.write("   source: s = manufacturer spec (curated), l = lamp/rated wattage (curated), o = Open Fixture Library\n")
        fh.write("   Open Fixture Library data (rev %s) is MIT licensed: Copyright (c) 2017 Florian & Felix Edelmann.\n" % ofl_rev)
        fh.write("   Curated list: data/touring-fixtures.json (%s). */\n" % curated.get("updated", ""))
        fh.write("(function(root){root.TS=root.TS||{};root.TS.FIXTURES=")
        json.dump(data, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";if(typeof module!==\"undefined\")module.exports=root.TS.FIXTURES})(typeof window!==\"undefined\"?window:globalThis);\n")
    print("wrote %s: %d fixtures (%d from OFL, %d curated)" % (out, len(data), ofl_count, len(curated["fixtures"])))

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
