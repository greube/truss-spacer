// Writes dist/sw.js listing every built file, so the app works offline.
// Scope-aware like the v1/v2 service workers: this copy only touches its own files and caches,
// because the live app, the v2 preview and this preview share one origin.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (n !== 'sw.js' && !n.endsWith('.map') && !/\.(txt|md)$/.test(n)) files.push(relative(dist, p).split(sep).join('/'));
  }
})(dist);
files.sort();
const BUILD = process.env.BUILD_ID || 'dev';

const sw = `/* Truss CAD service worker (generated by scripts/build-sw.mjs). */
const BUILD = ${JSON.stringify(BUILD)};
const SCOPE = new URL(self.registration.scope).pathname;
const PREFIX = "tcad:" + SCOPE + ":";
const VERSION = PREFIX + BUILD;
const ASSETS = ${JSON.stringify(['./', ...files], null, 1)};
const OWN = new Set(ASSETS.map(a => new URL(a, self.registration.scope).pathname));

self.addEventListener("install", e => {
  // cache: "reload" skips the HTTP cache (GitHub Pages allows 10 minutes) so a new version never saves stale files
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(ASSETS.map(a => new Request(a, { cache: "reload" })))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  // only this copy's own old caches
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  const shell = req.mode === "navigate" && (url.pathname === SCOPE || url.pathname === SCOPE + "index.html");
  if (!shell && !OWN.has(url.pathname)) return;
  const key = shell ? SCOPE + "index.html" : url.pathname;
  e.respondWith(caches.open(VERSION).then(async cache => {
    const hit = await cache.match(key, { ignoreSearch: shell });
    const net = fetch(url.href, { cache: "no-cache" }).then(res => { if (res && res.ok && res.type === "basic") cache.put(key, res.clone()); return res; }).catch(() => null);
    if (hit) { e.waitUntil(net); return hit; }
    return (await net) || new Response("Offline", { status: 503, statusText: "Offline" });
  }));
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw.js: ${files.length + 1} assets, build ${BUILD}`);
